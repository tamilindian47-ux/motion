import base64
import gc
import io
import logging
import math
import os
from pathlib import Path
import subprocess
import tempfile
import threading
import time

import runpod
import torch

from diffusers import (
    AutoencoderKLWan,
    UniPCMultistepScheduler,
    WanImageToVideoPipeline,
)

from diffusers.utils import export_to_video
from PIL import Image, ImageOps


logging.basicConfig(level=logging.INFO)
log = logging.getLogger("wan-story")

MODEL_DIR = os.environ.get(
    "MODEL_DIR",
    "/models/wan-turbo",
)

FPS = 24
GENERATED_FRAMES = 121
SAVED_FRAMES_PER_SEGMENT = 120
MAX_OUTPUT_BYTES = 6_000_000

Image.MAX_IMAGE_PIXELS = 25_000_000

PIPELINE = None
LOCK = threading.Lock()


def progress(job, message):
    log.info(message)
    runpod.serverless.progress_update(job, message)


def load_pipeline():
    if not torch.cuda.is_available():
        raise RuntimeError("No CUDA GPU detected.")

    log.info(
        "Loading pipeline on GPU: %s",
        torch.cuda.get_device_name(0),
    )

    vae = AutoencoderKLWan.from_pretrained(
        MODEL_DIR,
        subfolder="vae",
        torch_dtype=torch.float32,
        local_files_only=True,
    )

    pipe = WanImageToVideoPipeline.from_pretrained(
        MODEL_DIR,
        vae=vae,
        torch_dtype=torch.bfloat16,
        local_files_only=True,
        low_cpu_mem_usage=True,
    )

    pipe.scheduler = UniPCMultistepScheduler.from_config(
        pipe.scheduler.config,
        flow_shift=5.0,
    )

    pipe.vae.enable_tiling()
    pipe.enable_model_cpu_offload(gpu_id=0)

    return pipe


def decode_image(encoded):
    if not isinstance(encoded, str) or not encoded:
        raise ValueError("image_base64 is required.")

    if len(encoded) > 5_400_000:
        raise ValueError("Use an image smaller than 4 MB.")

    if encoded.startswith("data:"):
        encoded = encoded.split(",", 1)[1]

    raw = base64.b64decode(
        encoded,
        validate=True,
    )

    if len(raw) > 4_000_000:
        raise ValueError("Use an image smaller than 4 MB.")

    with Image.open(io.BytesIO(raw)) as source:
        image = ImageOps.exif_transpose(source).convert("RGB")
        image.load()

    if min(image.size) < 64:
        raise ValueError("Input image dimensions are too small.")

    ratio = image.width / image.height

    if not 0.4 <= ratio <= 2.5:
        raise ValueError(
            "Use a normal landscape or portrait image."
        )

    return image


def prepare_image(image, pipe):
    max_area = 1280 * 704

    multiple = int(
        pipe.vae_scale_factor_spatial
        * pipe.transformer.config.patch_size[1]
    )

    ratio = image.width / image.height

    width = (
        round(math.sqrt(max_area * ratio))
        // multiple
        * multiple
    )

    height = (
        round(math.sqrt(max_area / ratio))
        // multiple
        * multiple
    )

    width = max(multiple, width)
    height = max(multiple, height)

    return (
        image.resize(
            (width, height),
            Image.Resampling.LANCZOS,
        ),
        width,
        height,
    )


def validate_prompts(data):
    prompts = data.get("prompts")

    if not isinstance(prompts, list) or len(prompts) != 3:
        raise ValueError(
            "prompts must contain exactly three scene prompts."
        )

    for index, prompt in enumerate(prompts, start=1):
        if (
            not isinstance(prompt, str)
            or not prompt.strip()
            or len(prompt) > 2000
        ):
            raise ValueError(
                f"Scene {index} needs a prompt of 1–2000 characters."
            )

    return [prompt.strip() for prompt in prompts]


def stitch_segments(folder, segment_paths):
    manifest = folder / "segments.txt"

    # All names are generated by this handler, not supplied by users.
    manifest.write_text(
        "".join(
            f"file '{path.name}'\n"
            for path in segment_paths
        ),
        encoding="utf-8",
    )

    # Target a compact inline response without changing dimensions.
    # Lower bitrate may reduce quality in detailed or fast-moving scenes.
    for bitrate in ("2400k", "1800k", "1200k"):
        target = folder / f"story-{bitrate}.mp4"

        command = [
            "ffmpeg",
            "-hide_banner",
            "-loglevel",
            "error",
            "-nostdin",
            "-y",
            "-f",
            "concat",
            "-safe",
            "1",
            "-i",
            str(manifest),
            "-map",
            "0:v:0",
            "-an",
            "-vf",
            "setpts=PTS-STARTPTS",
            "-r",
            str(FPS),
            "-frames:v",
            "360",
            "-c:v",
            "libx264",
            "-preset",
            "fast",
            "-b:v",
            bitrate,
            "-pix_fmt",
            "yuv420p",
            "-movflags",
            "+faststart",
            str(target),
        ]

        subprocess.run(
            command,
            check=True,
            timeout=300,
        )

        if target.stat().st_size <= MAX_OUTPUT_BYTES:
            return target.read_bytes(), bitrate

    raise RuntimeError(
        "The final video exceeds the inline output limit. "
        "Object-storage output is needed for a larger file."
    )


def run_story(job, data):
    global PIPELINE

    prompts = validate_prompts(data)

    common_prompt = data.get(
        "common_prompt",
        (
            "The same people, clothing, lighting and location "
            "throughout. Realistic natural movement. "
            "A stable camera and continuous composition."
        ),
    )

    if (
        not isinstance(common_prompt, str)
        or len(common_prompt) > 2000
    ):
        raise ValueError(
            "common_prompt must be at most 2000 characters."
        )

    seed = int(data.get("seed", 42))

    if not 0 <= seed <= 2_147_483_644:
        raise ValueError(
            "seed must be between 0 and 2147483644."
        )

    image = decode_image(data.get("image_base64"))

    timings = []
    job_started = time.perf_counter()
    load_seconds = 0.0
    cold_load = PIPELINE is None

    if PIPELINE is None:
        progress(job, "Loading Turbo pipeline.")

        started = time.perf_counter()
        PIPELINE = load_pipeline()
        load_seconds = time.perf_counter() - started

    pipe = PIPELINE

    current_image, width, height = prepare_image(
        image,
        pipe,
    )

    torch.cuda.reset_peak_memory_stats()

    with tempfile.TemporaryDirectory(
        prefix="wan-story-"
    ) as temporary:
        folder = Path(temporary)
        segment_paths = []

        for index, action in enumerate(prompts):
            scene_number = index + 1

            progress(
                job,
                f"Generating scene {scene_number}/3: {action}",
            )

            started = time.perf_counter()

            full_prompt = (
                common_prompt.strip()
                + "\n"
                + action
            )

            generator = torch.Generator(
                device="cuda"
            ).manual_seed(seed + index)

            with torch.inference_mode():
                result = pipe(
                    image=current_image,
                    prompt=full_prompt,
                    width=width,
                    height=height,
                    num_frames=GENERATED_FRAMES,
                    num_inference_steps=4,
                    guidance_scale=1.0,
                    generator=generator,
                    output_type="pil",
                )

            frames = result.frames[0]

            if len(frames) != GENERATED_FRAMES:
                raise RuntimeError(
                    f"Scene {scene_number} returned "
                    f"{len(frames)} frames; expected 121."
                )

            if not isinstance(frames[-1], Image.Image):
                raise RuntimeError(
                    "Expected PIL image frames from the pipeline."
                )

            # This is the automatic continuation:
            # the final generated frame becomes the next input.
            current_image = frames[-1].convert("RGB").copy()

            torch.cuda.synchronize()

            generation_seconds = (
                time.perf_counter() - started
            )

            progress(
                job,
                f"Encoding scene {scene_number}/3.",
            )

            segment_path = (
                folder / f"segment-{scene_number}.mp4"
            )

            # Keep frames 1..120, dropping frame 0.
            # This avoids carrying the conditioning/start frame
            # as an extra frame at every boundary.
            #
            # Each saved segment:
            # 120 frames / 24 fps = exactly 5 seconds.
            export_to_video(
                frames[1:],
                str(segment_path),
                fps=FPS,
                quality=8,
                macro_block_size=1,
            )

            segment_paths.append(segment_path)

            timings.append({
                "scene": scene_number,
                "generation_seconds": round(
                    generation_seconds, 2
                ),
            })

            del frames, result
            gc.collect()
            torch.cuda.empty_cache()

        progress(
            job,
            "Joining all three scenes into the 15-second movie.",
        )

        encode_started = time.perf_counter()

        video_bytes, bitrate = stitch_segments(
            folder,
            segment_paths,
        )

        final_encode_seconds = (
            time.perf_counter() - encode_started
        )

    return {
        "video_base64": base64.b64encode(
            video_bytes
        ).decode("ascii"),
        "mime_type": "video/mp4",
        "duration_seconds": 15,
        "frames": 360,
        "fps": FPS,
        "width": width,
        "height": height,
        "segments": 3,
        "steps_per_segment": 4,
        "seed": seed,
        "cold_model_load": cold_load,
        "encoding_target_bitrate": bitrate,
        "file_bytes": len(video_bytes),
        "peak_allocated_vram_gb": round(
            torch.cuda.max_memory_allocated() / (1024**3),
            2,
        ),
        "timing": {
            "model_load_seconds": round(load_seconds, 2),
            "scenes": timings,
            "final_encode_seconds": round(
                final_encode_seconds, 2
            ),
            "handler_seconds": round(
                time.perf_counter() - job_started, 2
            ),
        },
    }


def handler(job):
    global PIPELINE

    with LOCK:
        try:
            return run_story(
                job,
                job.get("input", {}),
            )

        except Exception:
            # Reset after failure so partially interrupted
            # offload state is not reused by the next job.
            PIPELINE = None
            log.exception("Story generation failed")
            raise

        finally:
            gc.collect()

            if torch.cuda.is_available():
                torch.cuda.empty_cache()


if __name__ == "__main__":
    runpod.serverless.start({
        "handler": handler,
    })
